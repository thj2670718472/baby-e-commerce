async function initBabyCulture() {
  try {
    let inserted = 0;
    let skipped = 0;

    for (const article of sampleArticles) {
      const existed = await baby_culture.findOne({ where: { title: article.title } });
      if (existed) {
        skipped += 1;
        continue;
      }
      await baby_culture.create(article);
      inserted += 1;
    }

    const total = await baby_culture.count();
    console.log(`新增 ${inserted} 篇，跳过已存在 ${skipped} 篇，当前共 ${total} 篇`);
  } catch (error) {
    console.error('初始化育儿知识失败:', error.message);
    throw error;
  }
}

// 支持直接运行，也被 init-db 复用
if (require.main === module) {
  initBabyCulture()
    .then(() => process.exit(0))
    .catch((error) => {
      console.error('初始化育儿知识失败:', error.message);
      process.exit(1);
    });
}

module.exports = { run: initBabyCulture };
